"""Copy Anthropic's mcp-builder skill into general/.

    python3 .claude/skills/stack/mcp/sync.py <checkout>   copy from a checkout of
        https://github.com/anthropics/skills
    python3 .claude/skills/stack/mcp/sync.py --check      verify general/ against
        the lists below, offline

Files are copied verbatim: the skill's whole folder, so
general/mcp-builder/ holds SKILL.md, reference/ and scripts/ as upstream has
them. The one change: a relative link to a file that is not taken becomes a
link to that file upstream, at the synced commit. To take or drop a skill,
edit the list and run the sync; never edit general/ by hand.
"""
import os, re, shutil, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "general")
UPSTREAM = "https://github.com/anthropics/skills"
LICENCE_NAME = "Apache-2.0"
LICENCE_COPY = "anthropic-skills-mcp-builder-LICENSE"

# Skills taken, as {name: folder in the upstream repo}. mcp-builder is the
# guide to designing an MCP server's tools. Its TypeScript and Python code is
# not what we build with (the server is Rust, see antilog.md), but the folder
# is copied whole so the references stay linked. Its LICENSE.txt is per skill.
# Left out on purpose: every other skill in the repository.
SKILLS = {"mcp-builder": "skills/mcp-builder"}

LINK = re.compile(r"\]\(([^)\s#]+)(#[^)\s]*)?\)")
SKIP_DIRS = {"__pycache__", ".git", "node_modules"}
SKIP_FILES = {".DS_Store"}


def is_taken(repo_rel):
    return any(repo_rel == d or repo_rel.startswith(d + "/") for d in SKILLS.values())


def walk(top):
    for dp, dns, fs in os.walk(top):
        dns[:] = sorted(d for d in dns if d not in SKIP_DIRS)
        for f in sorted(fs):
            if f not in SKIP_FILES:
                yield os.path.join(dp, f)


def rewrite(text, repo_rel, root, commit):
    def fix(m):
        target, frag = m.group(1), m.group(2) or ""
        if re.match(r"^[a-z]+:", target) or target.startswith("/"):
            return m.group(0)
        resolved = os.path.normpath(os.path.join(os.path.dirname(repo_rel), target))
        if resolved.startswith(".."):
            return m.group(0)
        full = os.path.join(root, resolved)
        if not os.path.exists(full):
            return m.group(0)  # not a real link (an example in prose or code)
        if is_taken(resolved):
            return m.group(0)
        kind = "tree" if os.path.isdir(full) else "blob"
        return f"]({UPSTREAM}/{kind}/{commit}/{resolved}{frag})"
    return LINK.sub(fix, text)


def description(text):
    m = re.search(r"^description:[ \t]*(.*)$", text, re.M)
    if not m:
        h = re.search(r"^#\s+(.+)$", text, re.M)
        return h.group(1).strip() if h else ""
    first = m.group(1).strip()
    if first[:1] in (">", "|"):
        out = []
        for line in text[m.end():].splitlines()[1:]:
            if line and not line[0].isspace():
                break
            if line.strip():
                out.append(line.strip())
        return " ".join(out)
    return first.strip("\"'")


def sync(co):
    commit = subprocess.check_output(["git", "-C", co, "rev-parse", "HEAD"], text=True).strip()
    missing = [n for n, p in SKILLS.items() if not os.path.isfile(os.path.join(co, p, "SKILL.md"))]
    if missing:
        sys.exit(f"not upstream (moved or removed): {missing}")
    shutil.rmtree(OUT, ignore_errors=True)
    os.makedirs(os.path.join(HERE, "licenses"), exist_ok=True)
    n = 0
    for name, path in SKILLS.items():
        top = os.path.join(co, path)
        for src in walk(top):
            repo_rel = os.path.relpath(src, co)
            dst = os.path.join(OUT, name, os.path.relpath(src, top))
            os.makedirs(os.path.dirname(dst), exist_ok=True)
            if src.endswith(".md"):
                open(dst, "w").write(rewrite(open(src).read(), repo_rel, co, commit))
            else:
                shutil.copy(src, dst)
            n += 1
    shutil.copy(os.path.join(co, SKILLS["mcp-builder"], "LICENSE.txt"), os.path.join(HERE, "licenses", LICENCE_COPY))
    lines = [
        "# MCP skills: index",
        "",
        f"Source: {UPSTREAM} at `{commit[:12]}`, {LICENCE_NAME} ([licence](../licenses/{LICENCE_COPY})).",
        "Generated by `sync.py`; do not edit. Links to files not taken point upstream.",
        "Read [../antilog.md](../antilog.md) first: it says where Antilog's own rules win.",
        "",
        "| Skill | Use it to |",
        "| --- | --- |",
    ]
    for name, path in SKILLS.items():
        d = description(open(os.path.join(co, path, "SKILL.md")).read())
        lines.append(f"| [{name}]({name}/SKILL.md) | {d.replace('|', '/')} |")
    lines.append("")
    open(os.path.join(OUT, "INDEX.md"), "w").write("\n".join(lines))
    print(f"{len(SKILLS)} skills, {n} files from {commit[:12]}")


def check():
    errors = []
    if not os.path.isdir(OUT):
        sys.exit("mcp skills: general/ is missing; run the sync")
    have = {os.path.relpath(p, OUT) for p in walk(OUT)}
    for n in SKILLS:
        if f"{n}/SKILL.md" not in have:
            errors.append(f"missing {n}/SKILL.md")
    errors += [f"not in the lists (remove it or add it and sync): {p}" for p in sorted(have)
               if p != "INDEX.md" and p.split("/")[0] not in SKILLS]
    index = open(os.path.join(OUT, "INDEX.md")).read() if "INDEX.md" in have else ""
    for n in SKILLS:
        if f"({n}/SKILL.md)" not in index:
            errors.append(f"INDEX.md does not list {n}")
    if not os.path.exists(os.path.join(HERE, "licenses", LICENCE_COPY)):
        errors.append(f"missing licenses/{LICENCE_COPY}")
    for e in errors:
        print("mcp skills:", e, file=sys.stderr)
    sys.exit(1 if errors else 0)


if __name__ == "__main__":
    if sys.argv[1:] == ["--check"]:
        check()
    elif len(sys.argv) == 2:
        sync(sys.argv[1])
    else:
        sys.exit(__doc__)
