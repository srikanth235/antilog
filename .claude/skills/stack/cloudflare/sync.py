"""Copy the Cloudflare skills Ratchet uses into general/.

    python3 .claude/skills/stack/cloudflare/sync.py <checkout>   copy from a checkout of
        https://github.com/cloudflare/skills
    python3 .claude/skills/stack/cloudflare/sync.py --check      verify general/ against
        the lists below, offline

Files are copied verbatim, keeping the upstream layout (skills/<name>/ becomes
general/<name>/). The one change: a relative link to a file that is not taken
becomes a link to that file upstream, at the synced commit. To take or drop a
skill or a product reference, edit the lists and run the sync; never edit
general/ by hand.
"""
import os, re, shutil, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "general")
UPSTREAM = "https://github.com/cloudflare/skills"
BLOB = UPSTREAM + "/blob/{commit}/skills/{path}"

# Whole skills taken (cf-cli is the command agents use; wrangler stays
# because cf hands Rust builds to it): the cloud shell (a Worker with one Durable Object per
# organization), its tooling, and the sandboxes behind Ratchet-managed.
# Left out on purpose: the Agents SDK, email, Cloudflare One, Turnstile,
# frameworks and Next.js, web-perf (the web guides cover it), and the
# stable and migration Sandbox skills (Ratchet-managed is new, so it starts
# on the next API).
SKILLS = "durable-objects workers-best-practices workers-development workers-profiling cf-cli wrangler sandbox-next".split()

# Product references taken from the `cloudflare` skill (its chooser page is
# not taken: the products are decided). Static assets serve the web app, D1
# is the directory, R2 holds exports, secrets-store holds Ratchet-managed
# connector secrets, containers run Ratchet-managed sandboxes.
REFERENCES = "bindings containers cron-triggers d1 observability r2 secrets-store static-assets".split()

LINK = re.compile(r"\]\(([^)\s#]+)(#[^)\s]*)?\)")


def taken(rel):
    """rel is a path under upstream skills/. Is it copied?"""
    parts = rel.split("/")
    if parts[0] in SKILLS:
        return True
    return parts[0] == "cloudflare" and len(parts) > 3 and parts[1] == "references" and parts[2] in REFERENCES


def sources(root):
    for dp, _, fs in os.walk(root):
        for f in fs:
            rel = os.path.relpath(os.path.join(dp, f), root)
            if taken(rel):
                yield rel


def rewrite(text, rel, root, commit):
    def fix(m):
        target, frag = m.group(1), m.group(2) or ""
        if re.match(r"^[a-z]+:", target) or target.startswith("/"):
            return m.group(0)
        resolved = os.path.normpath(os.path.join(os.path.dirname(rel), target))
        if taken(resolved) and os.path.exists(os.path.join(root, resolved)):
            return m.group(0)
        if not os.path.exists(os.path.join(root, resolved)):
            sys.exit(f"{rel}: broken upstream link {target}")
        return f"]({BLOB.format(commit=commit, path=resolved)}{frag})"
    return LINK.sub(fix, text)


def description(text):
    m = re.search(r"^description:\s*(.+)$", text, re.M)
    if m:
        return m.group(1).strip().strip('"')
    m = re.search(r"^#\s+(.+)$", text, re.M)
    return m.group(1).strip() if m else ""


def sync(checkout):
    commit = subprocess.check_output(["git", "-C", checkout, "rev-parse", "HEAD"], text=True).strip()
    root = os.path.join(checkout, "skills")
    missing = [s for s in SKILLS if not os.path.isfile(os.path.join(root, s, "SKILL.md"))]
    missing += [r for r in REFERENCES if not os.path.isdir(os.path.join(root, "cloudflare", "references", r))]
    if missing:
        sys.exit(f"not upstream (moved or removed): {missing}")
    shutil.rmtree(OUT, ignore_errors=True)
    for rel in sorted(sources(root)):
        dst = os.path.join(OUT, rel)
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        src = os.path.join(root, rel)
        if rel.endswith(".md"):
            open(dst, "w").write(rewrite(open(src).read(), rel, root, commit))
        else:
            shutil.copy(src, dst)
    os.makedirs(os.path.join(HERE, "licenses"), exist_ok=True)
    shutil.copy(os.path.join(checkout, "LICENSE"), os.path.join(HERE, "licenses", "cloudflare-skills-LICENSE"))

    lines = [
        "# Cloudflare skills: index",
        "",
        f"Source: {UPSTREAM} at `{commit[:12]}`, Apache-2.0 ([licence](../licenses/cloudflare-skills-LICENSE)).",
        "Generated by `sync.py`; do not edit. Links to files not taken point upstream.",
        "Read [../ratchet.md](../ratchet.md) first: it says where Ratchet's own rules win.",
        "",
        "## Skills",
        "",
        "| Skill | Use it to |",
        "| --- | --- |",
    ]
    for s in SKILLS:
        d = description(open(os.path.join(root, s, "SKILL.md")).read())
        lines.append(f"| [{s}]({s}/SKILL.md) | {d.replace('|', '/')} |")
    lines += ["", "## Product references", "", "| Product | Start at |", "| --- | --- |"]
    for r in REFERENCES:
        lines.append(f"| {r} | [README](cloudflare/references/{r}/README.md) |")
    lines.append("")
    open(os.path.join(OUT, "INDEX.md"), "w").write("\n".join(lines))
    print(f"{len(SKILLS)} skills, {len(REFERENCES)} references from {commit[:12]}")


def check():
    errors = []
    if not os.path.isdir(OUT):
        sys.exit("cloudflare skills: general/ is missing; run the sync")
    have = {os.path.relpath(os.path.join(dp, f), OUT) for dp, _, fs in os.walk(OUT) for f in fs}
    errors += [f"missing {s}/SKILL.md" for s in SKILLS if f"{s}/SKILL.md" not in have]
    errors += [f"missing reference {r}" for r in REFERENCES if f"cloudflare/references/{r}/README.md" not in have]
    errors += [f"not in the lists (remove it or add it and sync): {p}" for p in sorted(have)
               if p != "INDEX.md" and not taken(p)]
    for p in sorted(have):
        if not p.endswith(".md"):
            continue
        for m in LINK.finditer(open(os.path.join(OUT, p)).read()):
            t = m.group(1)
            if re.match(r"^[a-z]+:", t) or t.startswith("/"):
                continue
            if not os.path.exists(os.path.join(OUT, os.path.dirname(p), t)):
                errors.append(f"{p}: broken link {t}")
    if not os.path.exists(os.path.join(HERE, "licenses", "cloudflare-skills-LICENSE")):
        errors.append("missing licenses/cloudflare-skills-LICENSE")
    for e in errors:
        print("cloudflare skills:", e, file=sys.stderr)
    sys.exit(1 if errors else 0)


if __name__ == "__main__":
    if sys.argv[1:] == ["--check"]:
        check()
    elif len(sys.argv) == 2:
        sync(sys.argv[1])
    else:
        sys.exit(__doc__)
