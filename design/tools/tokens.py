#!/usr/bin/env python3
"""Generate the Ratchet mockup foundation from design/tokens.toml (standard library only).

    python3 design/tools/tokens.py           write the generated files
    python3 design/tools/tokens.py --check   write nothing; exit 1 listing every problem

Writes, under design/mockups/:
  tokens.css        light colours on :root, dark on [data-theme="dark"], the type classes
                    (.t-hero .t-display .t-title .t-section .t-item .t-body .t-meta .t-label
                    .t-big) and the base rules for a board root (.board).
  XDark.dc.html     for every board on a "*-light" page of canvas.json: the same file with
                    data-theme="dark" on the board root, "dark" in the title and every link
                    href="Y.dc.html" rewritten to "YDark.dc.html" and dark="1" added to every
                    <dc-import> so a click stays in dark. Boards on other pages (rules,
                    components) get no twin; components inherit the theme of their board.
  canvas.json       the twin's entry on the matching "*-dark" page, same x/y/w/h. Humans own
                    the light entries; this tool owns the dark ones.

--check regenerates in memory and reports: changed, missing or stray generated files; a raw
colour (hex, rgb(), hsl(), a colour name) in the style or colour attributes or a <style> of a
board outside an element marked data-keep (third-party logos); a data-go whose X.dc.html does
not exist; a board file not in canvas.json or an entry without a file; and, in DesignRules, a
token value or contrast ratio that does not match tokens.toml.
(target) The Mac app's Swift colours are a future output of this tool.
"""
import json, re, sys, tomllib
from html.parser import HTMLParser
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOKENS, MOCK = ROOT / "tokens.toml", ROOT / "mockups"
CANVAS = MOCK / "canvas.json"
TYPE_CLASSES = {"hero": "t-hero", "display": "t-display", "title": "t-title", "section": "t-section",
                "item": "t-item", "body": "t-body", "meta": "t-meta", "label": "t-label", "big": "t-big"}
COLOR_ATTRS = {"style", "fill", "stroke", "stop-color", "flood-color", "color", "bgcolor"}
VOID = set("area base br col embed hr img input link meta source track wbr".split())
NAMES = set("white black red green blue gray grey yellow orange purple pink brown cyan magenta navy "
            "teal silver gold maroon olive lime aqua fuchsia ivory beige tan salmon coral crimson "
            "indigo violet khaki lavender".split())
HEX = re.compile(r"(?<![\w&])#[0-9a-fA-F]{3,8}\b")
FUNC = re.compile(r"\b(?:rgb|rgba|hsl|hsla|hwb|lab|lch|oklch|oklab)\(")
WORD = re.compile(r"(?<![\w-])([a-z]+)(?![\w-])")


def load():
    return tomllib.loads(TOKENS.read_text())


def css(t):
    out = ["/* Generated by design/tools/tokens.py from design/tokens.toml. Never edit. */"]
    cvars = lambda c: "".join(f"--{k}:{v};" for k, v in c.items())
    misc = "".join(f"--font-{k}:{v};" for k, v in t["font"].items())
    misc += "".join(f"--{k}:{v}{'px' if k != 'pill' else 'px'};" for k, v in t["radius"].items())
    misc += "".join(f"--{k}:{v}px;" for k, v in t["space"].items())
    out.append(f":root{{color-scheme:light;{cvars(t['color']['light'])}{misc}}}")
    out.append(f"[data-theme=\"dark\"]{{color-scheme:dark;{cvars(t['color']['dark'])}}}")
    b = t["type"]["body"]
    out.append(f"body{{margin:0;background:var(--canvas);color:var(--ink);font:{b['weight']} {b['size']}px/{b['line']} var(--font-{b['family']})}}")
    out.append(f"html:has([data-theme=\"dark\"]){{background:{t['color']['dark']['canvas']}}}")
    out.append(f".board{{background:var(--canvas);color:var(--ink);font:{b['weight']} {b['size']}px/{b['line']} var(--font-{b['family']});"
               "-webkit-font-smoothing:antialiased;box-sizing:border-box}")
    out.append(".board *,.board *::before,.board *::after{box-sizing:border-box}")
    out.append(".board button,.board input,.board textarea,.board select{font:inherit;color:inherit}")
    out.append(".mono{font-family:var(--font-mono)}")
    for name, cls in TYPE_CLASSES.items():
        s = t["type"][name]
        r = f".{cls}{{margin:0;font:{s['weight']} {s['size']}px/{s['line']} var(--font-{s['family']});"
        if s["tracking"] != "0":
            r += f"letter-spacing:{s['tracking']};"
        if s.get("transform"):
            r += f"text-transform:{s['transform']};"
        if s.get("tabular"):
            r += "font-variant-numeric:tabular-nums;"
        if name in ("meta", "label"):
            r += "color:var(--ink3);"
        out.append(r + "}")
    return "\n".join(out) + "\n"


def canvas_and_twins():
    """Return (canvas dict, {twin filename: text}, set of light boards)."""
    cv = json.loads(CANVAS.read_text())
    twins, new_boards = {}, {}
    light = {k for k, v in cv["boards"].items() if v["page"].endswith("-light")}
    for name, e in cv["boards"].items():
        if not e["page"].endswith("-dark"):
            new_boards[name] = e
    for name, e in list(new_boards.items()):
        if not e["page"].endswith("-light"):
            continue
        twin = name.replace(".dc.html", "Dark.dc.html")
        src = MOCK / name
        if src.exists():
            txt = src.read_text()
            txt = re.sub(r"<title>(.*?)</title>", lambda m: f"<title>{m.group(1)} · dark</title>", txt, count=1)
            txt = re.sub(r"(</helmet>\s*<div)(?![^>]*data-theme)", r'\1 data-theme="dark"', txt, count=1)
            txt = re.sub(r'href="(\w+)\.dc\.html"', lambda m: f'href="{m.group(1)}Dark.dc.html"' if f"{m.group(1)}.dc.html" in light else m.group(0), txt)
            txt = txt.replace("<dc-import ", '<dc-import dark="1" ')  # components keep their links in dark
            twins[twin] = txt
        d = dict(e, page=e["page"][:-6] + "-dark", title=e["title"] + " · dark")
        new_boards[twin] = d
    cv["boards"] = dict(sorted(new_boards.items()))
    cv["order"] = [f for f in sorted(cv["boards"])]
    return cv, twins


class Scan(HTMLParser):
    """Walks a board: raw colours outside data-keep, data-go targets, text nodes, data-ratio spans."""
    def __init__(self):
        super().__init__()
        self.stack, self.problems, self.gos, self.text, self.ratios, self._r = [], [], [], [], {}, None
        self.imports, self.nexts = [], []

    def keep(self):
        return any(k for _, k, _ in self.stack)

    def raw(self, v):
        v = re.sub(r"var\([^)]*\)|url\([^)]*\)|[\"'][^\"']*[\"']", "", v)
        return bool(HEX.search(v) or FUNC.search(v) or any(w in NAMES for w in WORD.findall(v)))

    def handle_starttag(self, tag, attrs, selfclose=False):
        a = dict(attrs)
        keep = "data-keep" in a
        m = tag == "a" and re.fullmatch(r"(\w+)\.dc\.html", a.get("href", ""))
        if m:
            self.gos.append(m.group(1))
        if tag == "dc-import" and a.get("name"):
            self.imports.append(a["name"])
        if "data-next" in a:
            self.nexts.append(a["data-next"])
        if tag == "button" and any(t == "a" and lk for t, _, lk in self.stack):
            self.problems.append("<button> inside a board link")
        if "data-ratio" in a:
            self._r = a["data-ratio"]
        if not (self.keep() or keep):
            for k, v in a.items():
                if k in COLOR_ATTRS and v and self.raw(v):
                    self.problems.append(f"raw colour in <{tag} {k}=\"{v[:50]}\">")
        if tag not in VOID and not selfclose:
            self.stack.append((tag, keep, bool(m)))

    def handle_startendtag(self, tag, attrs):
        self.handle_starttag(tag, attrs, True)

    def handle_endtag(self, tag):
        while self.stack:
            if self.stack.pop()[0] == tag:
                break

    def handle_data(self, d):
        if self.stack and self.stack[-1][0] == "style" and not self.keep() and self.raw(d):
            self.problems.append("raw colour in a <style> block")
        if self._r and d.strip():
            self.ratios[self._r] = d.strip()
            self._r = None
        if not self.keep():
            self.text.append(d)


def lum(c):
    r, g, b = (int(c[i:i + 2], 16) / 255 for i in (1, 3, 5))
    f = lambda v: v / 12.92 if v <= .03928 else ((v + .055) / 1.055) ** 2.4
    return .2126 * f(r) + .7152 * f(g) + .0722 * f(b)


def ratio(a, b):
    x, y = sorted((lum(a), lum(b)), reverse=True)
    return (x + .05) / (y + .05)


def rules_problems(t, scan):
    p = []
    vals = {v for th in ("light", "dark") for v in t["color"][th].values() if v.startswith("#")}
    shown = set(re.findall(r"#[0-9A-F]{6}\b", "\n".join(scan.text)))
    p += [f"DesignRules shows {v}, not in tokens.toml" for v in sorted(shown - vals)]
    p += [f"DesignRules does not show {v}" for v in sorted(vals - shown)]
    for key, got in scan.ratios.items():
        th, pair = key.split(":")
        fg, _, bg = pair.partition("/")
        c = t["color"][th]
        want = f"{ratio(c[fg], c[bg or 'canvas']):.1f}"
        if got != want:
            p.append(f"DesignRules ratio {key} is {got}, should be {want}")
    return p


def main():
    check = "--check" in sys.argv
    t = load()
    cv, twins = canvas_and_twins()
    want = {MOCK / "tokens.css": css(t), CANVAS: json.dumps(cv, indent=2) + "\n"}
    want.update({MOCK / k: v for k, v in twins.items()})
    problems = []
    existing_twins = {p for p in MOCK.glob("*Dark.dc.html")}
    for f, txt in want.items():
        if not f.exists():
            problems.append(f"missing generated file {f.name}")
        elif f.read_text() != txt:
            problems.append(f"changed generated file {f.name} (run tokens.py)")
    for f in existing_twins - set(want):
        problems.append(f"stray generated file {f.name}")
    planned, files = set(), {p.name for p in MOCK.glob("*.dc.html")}
    for f in sorted(files - set(cv["boards"])):
        problems.append(f"board file not in canvas.json: {f}")
    for f in sorted(set(cv["boards"]) - files - set(twins)):
        problems.append(f"canvas.json entry without a file: {f}")
    for f in sorted(files):
        if f.endswith("Dark.dc.html") and (MOCK / f) in want:
            continue  # twins are compared above; their light source is scanned below
        s = Scan()
        src = (MOCK / f).read_text()
        s.feed(src)
        problems += [f"{f}: {x}" for x in s.problems]
        have = lambda g: (MOCK / f"{g}.dc.html").exists()
        problems += [f"{f}: link to {g}.dc.html, which does not exist" for g in sorted(set(s.gos)) if not have(g)]
        problems += [f"{f}: <dc-import name=\"{g}\"> has no {g}.dc.html" for g in sorted(set(s.imports)) if not have(g)]
        problems += [f"{f}: data-next=\"{g}\" now exists, make it a link" for g in sorted(set(s.nexts)) if have(g)]
        planned |= {g for g in s.nexts if not have(g)}
        # components list the boards their script links to in a "// links: A B" comment; a missing one is planned
        planned |= {g for m in re.findall(r"// links: (.*)", src) for g in m.split() if not have(g)}
        page = cv["boards"].get(f, {}).get("page")
        if (s.gos or s.imports) and page not in ("components", None) and not cv["boards"][f].get("is_interactive"):
            problems.append(f"{f}: has links or imports but its canvas entry lacks is_interactive")
        if f == "DesignRules.dc.html":
            problems += [f"{f}: {x}" for x in rules_problems(t, s)]
    for f in ("components.css", "icons.css"):  # authored stylesheets: values only through var()
        body = re.sub(r"/\*.*?\*/", "", (MOCK / f).read_text(), flags=re.S)
        if Scan().raw(body):
            problems.append(f"{f}: raw colour (use var(--token))")
    if check:
        for x in problems:
            print("FAIL", x)
        print("planned boards not drawn yet:", " ".join(sorted(planned)) or "none")
        print("design check:", "failed" if problems else "ok")
        sys.exit(1 if problems else 0)
    for f, txt in want.items():
        f.write_text(txt)
    for f in existing_twins - set(want):
        f.unlink()
    print(f"wrote tokens.css, canvas.json and {len(twins)} dark twin(s)")


if __name__ == "__main__":
    main()
