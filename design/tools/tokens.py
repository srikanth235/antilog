#!/usr/bin/env python3
"""Generate the Ratchet mockup foundation from design/tokens.toml (standard library only).

    python3 design/tools/tokens.py           write the generated files
    python3 design/tools/tokens.py --check   write nothing; exit 1 listing every problem

Writes, under design/mockups/:
  tokens.css        light colours on :root, dark on [data-theme="dark"], the type classes
                    (.t-hero .t-display .t-title .t-section .t-item .t-body .t-meta .t-label
                    .t-big) and the base rules for a board root (.board).
  XDark.dc.html     for every board on a "*-light" page of canvas.json: the same file with
                    data-theme="dark" on the board root, "dark" in the title and every
                    href="Y.dc.html" rewritten to "YDark.dc.html" (inserted parts included),
                    so a click stays in dark. Boards on other pages (rules, components) get
                    no twin.
  parts             in every board, <!-- part:Name key="v" --> ... <!-- /part --> is rewritten
                    to hold the content of Name.dc.html (the inside of its display:contents
                    wrapper). active="x" puts aria-current="page" on the element with
                    data-item="x"; any other key="v" replaces the text of the element with
                    data-slot="key". Parts may nest; a cycle is an error. A nested marker takes
                    its own keys; active on an outer marker reaches the data-item inside nested
                    parts. variant="mac" sets href to the element's data-mac value (the Mac
                    boards for the rows that open a thread). A part edited inside a nested part
                    is reported by the nested part's name.
  logos.css         from design/logos/logos.toml and its SVGs: .lg-NAME for each third-party
                    mark (brand colour, or the ink token when mono = true), and .lgt, a text
                    tile for brands with no mark we may use.
  canvas.json       the twin's entry on the matching "*-dark" page, same x/y/w/h. Humans own
                    the light entries; this tool owns the dark ones.

--check regenerates in memory and reports: changed, missing or stray generated files; a raw
colour (hex, rgb(), hsl(), a colour name) in the style or colour attributes or a <style> of a
board outside an element marked data-keep (third-party logos); any <dc-import>, {{ }}, <sc-for>
or <sc-if> in a board; part content that is not what the generator writes (edit the part file);
an unknown part, or a part marker without its closing marker; a link whose X.dc.html does
not exist; a board file not in canvas.json or an entry without a file; and, in DesignRules, a
token value or contrast ratio that does not match tokens.toml.
(target) The Mac app's Swift colours are a future output of this tool.
"""
import json, re, sys, tomllib
from html.parser import HTMLParser
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOKENS, MOCK = ROOT / "tokens.toml", ROOT / "mockups"
LOGOS = ROOT / "logos"
CANVAS = MOCK / "canvas.json"
TYPE_CLASSES = {"hero": "t-hero", "display": "t-display", "title": "t-title", "section": "t-section",
                "item": "t-item", "body": "t-body", "meta": "t-meta", "label": "t-label", "big": "t-big"}
COLOR_ATTRS = {"style", "fill", "stroke", "stop-color", "flood-color", "color", "bgcolor"}
VOID = set("area base br col embed hr img input link meta source track wbr".split())
NAMES = set("white black red green blue gray grey yellow orange purple pink brown cyan magenta navy "
            "teal silver gold maroon olive lime aqua fuchsia ivory beige tan salmon coral crimson "
            "indigo violet khaki lavender".split())
HEX = re.compile(r"(?<![\w&])#[0-9a-fA-F]{3,8}\b")
FUNC = re.compile(r"\b(?:rgb|rgba|hsl|hsla|hwb|lab|lch|oklch|oklab)\(")
WORD = re.compile(r"(?<![\w-])([a-z]+)(?![\w-])")


def load():
    return tomllib.loads(TOKENS.read_text())


def css(t):
    out = ["/* Generated by design/tools/tokens.py from design/tokens.toml. Never edit. */"]
    cvars = lambda c: "".join(f"--{k}:{v};" for k, v in c.items())
    misc = "".join(f"--font-{k}:{v};" for k, v in t["font"].items())
    misc += "".join(f"--{k}:{v}{'px' if k != 'pill' else 'px'};" for k, v in t["radius"].items())
    misc += "".join(f"--{k}:{v}px;" for k, v in t["space"].items())
    out.append(f":root{{color-scheme:light;{cvars(t['color']['light'])}{misc}}}")
    out.append(f"[data-theme=\"dark\"]{{color-scheme:dark;{cvars(t['color']['dark'])}}}")
    b = t["type"]["body"]
    out.append(f"body{{margin:0;background:var(--canvas);color:var(--ink);font:{b['weight']} {b['size']}px/{b['line']} var(--font-{b['family']})}}")
    out.append(f"html:has([data-theme=\"dark\"]){{background:{t['color']['dark']['canvas']}}}")
    out.append(f".board{{background:var(--canvas);color:var(--ink);font:{b['weight']} {b['size']}px/{b['line']} var(--font-{b['family']});"
               "-webkit-font-smoothing:antialiased;box-sizing:border-box}")
    out.append(".board *,.board *::before,.board *::after{box-sizing:border-box}")
    out.append(".board button,.board input,.board textarea,.board select{font:inherit;color:inherit}")
    out.append(".mono{font-family:var(--font-mono)}")
    for name, cls in TYPE_CLASSES.items():
        s = t["type"][name]
        r = f".{cls}{{margin:0;font:{s['weight']} {s['size']}px/{s['line']} var(--font-{s['family']});"
        if s["tracking"] != "0":
            r += f"letter-spacing:{s['tracking']};"
        if s.get("transform"):
            r += f"text-transform:{s['transform']};"
        if s.get("tabular"):
            r += "font-variant-numeric:tabular-nums;"
        if name in ("meta", "label"):
            r += "color:var(--ink3);"
        out.append(r + "}")
    return "\n".join(out) + "\n"


PART_OPEN = re.compile(r"^([ \t]*)<!-- part:(\w+)((?:\s+[\w-]+=\"[^\"]*\")*)\s*-->[ \t]*$", re.M)
PART_ANY = re.compile(r"<!-- part:|<!-- /part -->")
WRAP = re.compile(r"</helmet>\s*<div class=\"board\" style=\"display: contents;\">\n(.*)\n</div>\s*</x-dc>", re.S)
RUNTIME = re.compile(r"<dc-import|\{\{|<sc-for|<sc-if")


class PartError(Exception):
    pass


def part_body(name, stack=()):
    """The flattened content of a part: its wrapper's inside, nested parts expanded, markers dropped."""
    f = MOCK / f"{name}.dc.html"
    if not f.exists():
        raise PartError(f"unknown part {name} (no {name}.dc.html)")
    if name in stack:
        raise PartError(f"part cycle: {' > '.join(stack + (name,))}")
    m = WRAP.search(f.read_text())
    if not m:
        raise PartError(f"{name}.dc.html has no <div class=\"board\" style=\"display: contents;\"> root inside <x-dc>")
    return flatten(m.group(1), stack + (name,), keep_markers=False)


def apply_params(name, body, attrs):
    for key, val in attrs.items():
        if key == "variant":
            if val != "mac":
                raise PartError(f"part {name}: unknown variant {val}")
            body = re.sub(r'href="[^"]*"([^>]*?) data-mac="([^"]*)"', r'href="\2"\1 data-mac="\2"', body)
        elif key == "active":
            tag = re.search(rf"<(\w+)\b[^>]*\bdata-item=\"{re.escape(val)}\"[^>]*>", body)
            if not tag:
                raise PartError(f"part {name}: no data-item=\"{val}\"")
            t = tag.group(0)
            if "aria-current" in t:
                continue
            body = body.replace(t, t[:-1] + ' aria-current="page">', 1)
        else:
            pat = re.compile(rf"(<(\w+)\b[^>]*\bdata-slot=\"{re.escape(key)}\"[^>]*>)(.*?)(</\2>)", re.S)
            if not pat.search(body):
                raise PartError(f"part {name}: no data-slot=\"{key}\"")
            body = pat.sub(lambda m: m.group(1) + val + m.group(4), body, count=1)
    return body


def flatten(text, stack=(), keep_markers=True):
    """Rewrite every part region in text. keep_markers=False drops the markers (for nesting)."""
    out, pos = [], 0
    while True:
        m = PART_OPEN.search(text, pos)
        if not m:
            break
        end = text.find("<!-- /part -->", m.end())
        if end < 0:
            raise PartError(f"part {m.group(2)} has no closing <!-- /part -->")
        out.append(text[pos:m.start()])
        indent, name = m.group(1), m.group(2)
        attrs = dict(re.findall(r"([\w-]+)=\"([^\"]*)\"", m.group(3)))
        body = apply_params(name, part_body(name, stack), attrs)
        body = "\n".join(indent + ln if ln else ln for ln in body.split("\n"))
        if keep_markers:
            out.append(f"{m.group(0)}\n{body}\n{indent}<!-- /part -->")
        else:
            out.append(body)
        pos = end + len("<!-- /part -->")
    out.append(text[pos:])
    res = "".join(out)
    if keep_markers and re.search(r"<!-- /part -->", re.sub(r"<!-- part:.*?<!-- /part -->", "", res, flags=re.S)):
        raise PartError("a closing <!-- /part --> has no opening marker")
    return res


def nested_names(name, seen=()):
    f = MOCK / f"{name}.dc.html"
    out = []
    for n in re.findall(r"<!-- part:(\w+)", f.read_text() if f.exists() else ""):
        if n not in seen:
            out += [n] + nested_names(n, seen + (n,))
    return out


def norm(ln):
    return re.sub(r'\s+aria-current="page"|href="[^"]*"', "", ln).strip()


def blame(name, src_region, want_region):
    """The deepest nested part whose own text holds a line that differs, else name."""
    import difflib
    a, b = src_region.split("\n"), want_region.split("\n")
    bad = [norm(l) for t, i1, i2, j1, j2 in difflib.SequenceMatcher(None, a, b).get_opcodes() if t != "equal" for l in b[j1:j2] + a[i1:i2]]
    for n in reversed(nested_names(name)):
        body = {norm(l) for l in part_body(n).split("\n")}
        if any(l in body for l in bad if l):
            return n
    return name


def part_drift(src, want):
    """Names of the parts whose region in src differs from what the generator writes."""
    names = []
    for a, b in zip(re.finditer(r"<!-- part:(\w+).*?<!-- /part -->", src, re.S), re.finditer(r"<!-- part:(\w+).*?<!-- /part -->", want, re.S)):
        if a.group(0) != b.group(0):
            names.append(blame(a.group(1), a.group(0), b.group(0)))
    return names


def canvas_and_twins(problems):
    """Return (canvas dict, {twin filename: text})."""
    cv = json.loads(CANVAS.read_text())
    twins, new_boards = {}, {}
    light = {k for k, v in cv["boards"].items() if v["page"].endswith("-light")}
    for name, e in cv["boards"].items():
        if not e["page"].endswith("-dark"):
            new_boards[name] = e
    for name, e in list(new_boards.items()):
        if not e["page"].endswith("-light"):
            continue
        twin = name.replace(".dc.html", "Dark.dc.html")
        src = MOCK / name
        if src.exists():
            try:
                txt = flatten(src.read_text())
            except PartError as e:
                problems.append(f"{name}: {e}")
                continue
            txt = re.sub(r"<title>(.*?)</title>", lambda m: f"<title>{m.group(1)} · dark</title>", txt, count=1)
            txt = re.sub(r"(</helmet>\s*<div)(?![^>]*data-theme)", r'\1 data-theme="dark"', txt, count=1)
            txt = re.sub(r'href="(\w+)\.dc\.html"', lambda m: f'href="{m.group(1)}Dark.dc.html"' if f"{m.group(1)}.dc.html" in light else m.group(0), txt)
            twins[twin] = txt
        d = dict(e, page=e["page"][:-6] + "-dark", title=e["title"] + " · dark")
        new_boards[twin] = d
    cv["boards"] = dict(sorted(new_boards.items()))
    cv["order"] = [f for f in sorted(cv["boards"])]
    return cv, twins


class Scan(HTMLParser):
    """Walks a board: raw colours outside data-keep, data-go targets, text nodes, data-ratio spans."""
    def __init__(self):
        super().__init__()
        self.stack, self.problems, self.gos, self.text, self.ratios, self._r = [], [], [], [], {}, None
        self.nexts, self.in_part, self.parts = [], 0, 0

    def keep(self):
        return any(k for _, k, _ in self.stack)

    def raw(self, v):
        v = re.sub(r"var\([^)]*\)|url\([^)]*\)|[\"'][^\"']*[\"']", "", v)
        return bool(HEX.search(v) or FUNC.search(v) or any(w in NAMES for w in WORD.findall(v)))

    def handle_starttag(self, tag, attrs, selfclose=False):
        a = dict(attrs)
        keep = "data-keep" in a
        m = tag == "a" and re.fullmatch(r"(\w+)\.dc\.html", a.get("href", ""))
        if m and not self.in_part:
            self.gos.append(m.group(1))
        if "data-next" in a:
            self.nexts.append(a["data-next"])
        if tag == "button" and any(t == "a" and lk for t, _, lk in self.stack):
            self.problems.append("<button> inside a board link")
        if "data-ratio" in a:
            self._r = a["data-ratio"]
        if not (self.keep() or keep):
            for k, v in a.items():
                if k in COLOR_ATTRS and v and self.raw(v):
                    self.problems.append(f"raw colour in <{tag} {k}=\"{v[:50]}\">")
        if tag not in VOID and not selfclose:
            self.stack.append((tag, keep, bool(m)))

    def handle_comment(self, data):
        d = data.strip()
        if d.startswith("part:"):
            self.in_part += 1
            self.parts += 1
        elif d == "/part":
            self.in_part = max(0, self.in_part - 1)

    def handle_startendtag(self, tag, attrs):
        self.handle_starttag(tag, attrs, True)

    def handle_endtag(self, tag):
        while self.stack:
            if self.stack.pop()[0] == tag:
                break

    def handle_data(self, d):
        if self.stack and self.stack[-1][0] == "style" and not self.keep() and self.raw(d):
            self.problems.append("raw colour in a <style> block")
        if self._r and d.strip():
            self.ratios[self._r] = d.strip()
            self._r = None
        if not self.keep():
            self.text.append(d)


def lum(c):
    r, g, b = (int(c[i:i + 2], 16) / 255 for i in (1, 3, 5))
    f = lambda v: v / 12.92 if v <= .03928 else ((v + .055) / 1.055) ** 2.4
    return .2126 * f(r) + .7152 * f(g) + .0722 * f(b)


def ratio(a, b):
    x, y = sorted((lum(a), lum(b)), reverse=True)
    return (x + .05) / (y + .05)


def rules_problems(t, scan):
    p = []
    vals = {v for th in ("light", "dark") for v in t["color"][th].values() if v.startswith("#")}
    shown = set(re.findall(r"#[0-9A-F]{6}\b", "\n".join(scan.text)))
    p += [f"DesignRules shows {v}, not in tokens.toml" for v in sorted(shown - vals)]
    p += [f"DesignRules does not show {v}" for v in sorted(vals - shown)]
    for key, got in scan.ratios.items():
        th, pair = key.split(":")
        fg, _, bg = pair.partition("/")
        c = t["color"][th]
        want = f"{ratio(c[fg], c[bg or 'canvas']):.1f}"
        if got != want:
            p.append(f"DesignRules ratio {key} is {got}, should be {want}")
    return p


def logos_css():
    """logos.css: third-party marks as backgrounds (brand colour) or masks (ink), and text tiles."""
    cfg = tomllib.loads((LOGOS / "logos.toml").read_text())
    out = ["/* Generated by design/tools/tokens.py from design/logos/; do not edit. Third-party marks:",
           "   Simple Icons (CC0), see design/logos/simple-icons-LICENSE.md. */",
           ".lg{display:inline-flex;align-items:center;justify-content:center;width:18px;height:18px;flex:none;"
           "background:no-repeat center/contain}",
           ".tile.lg .lg{width:24px;height:24px}.sd-nav .lg{width:16px;height:16px}",
           ".lgt{width:auto;min-width:18px;font:600 9.5px/1 var(--font-mono);letter-spacing:-.02em;color:var(--ink2)}"]
    for name, m in cfg["mark"].items():
        svg = (LOGOS / f"{name}.svg").read_text()
        path = "".join(re.findall(r'<path d="([^"]+)"', svg))
        if not path:
            raise SystemExit(f"logos: no path in {name}.svg")
        fill = "black" if m.get("mono") else f"%23{m['hex']}"
        url = f"url(\"data:image/svg+xml,<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 24 24'><path fill='{fill}' d='{path}'/></svg>\")"
        out.append(f".lg-{name}{{--lg:{url}}}" if m.get("mono") else f".lg-{name}{{background-image:{url}}}")
    mono = ",".join(f".lg-{n}" for n, m in cfg["mark"].items() if m.get("mono"))
    out.append(mono + "{background:var(--ink);-webkit-mask:var(--lg) no-repeat center/contain;mask:var(--lg) no-repeat center/contain}")
    return "\n".join(out) + "\n"


def main():
    check = "--check" in sys.argv
    t = load()
    problems = []
    cv, twins = canvas_and_twins(problems)
    want = {MOCK / "tokens.css": css(t), MOCK / "logos.css": logos_css(), CANVAS: json.dumps(cv, indent=2) + "\n"}
    want.update({MOCK / k: v for k, v in twins.items()})
    for f in sorted(MOCK.glob("*.dc.html")):  # light boards and parts: part regions must be what the generator writes
        if f.name in twins:
            continue
        src = f.read_text()
        try:
            want[f] = flatten(src)
        except PartError as e:
            problems.append(f"{f.name}: {e}")
            continue
        if want[f] != src and check:
            for n in part_drift(src, want[f]):
                problems.append(f"{f.name}: part {n} is not what the generator writes; edit {n}.dc.html, not {f.name}, then run the generator")
            want.pop(f)
        if RUNTIME.search(src):
            problems.append(f"{f.name}: <dc-import>, {{{{ }}}}, <sc-for> or <sc-if> (boards and parts are plain static files)")
    existing_twins = {p for p in MOCK.glob("*Dark.dc.html")}
    for f, txt in want.items():
        if not f.exists():
            problems.append(f"missing generated file {f.name}")
        elif f.read_text() != txt:
            problems.append(f"changed generated file {f.name} (run tokens.py)")
    for f in existing_twins - set(want):
        problems.append(f"stray generated file {f.name}")
    planned, files = set(), {p.name for p in MOCK.glob("*.dc.html")}
    for f in sorted(files - set(cv["boards"])):
        problems.append(f"board file not in canvas.json: {f}")
    for f in sorted(set(cv["boards"]) - files - set(twins)):
        problems.append(f"canvas.json entry without a file: {f}")
    for f in sorted(files):
        if f.endswith("Dark.dc.html") and (MOCK / f) in want:
            continue  # twins are compared above; their light source is scanned below
        s = Scan()
        src = (MOCK / f).read_text()
        s.feed(src)
        problems += [f"{f}: {x}" for x in s.problems]
        have = lambda g: (MOCK / f"{g}.dc.html").exists()
        is_part = cv["boards"].get(f, {}).get("page") == "components"
        if is_part:  # a part's links to boards not drawn yet are planned
            planned |= {g for g in s.gos if not have(g)}
        else:
            problems += [f"{f}: link to {g}.dc.html, which does not exist" for g in sorted(set(s.gos)) if not have(g)]
        problems += [f"{f}: data-next=\"{g}\" now exists, make it a link" for g in sorted(set(s.nexts)) if have(g)]
        planned |= {g for g in s.nexts if not have(g)}
        page = cv["boards"].get(f, {}).get("page")
        if (s.gos or s.parts) and page not in ("components", None) and not cv["boards"][f].get("is_interactive"):
            problems.append(f"{f}: has links or parts but its canvas entry lacks is_interactive")
        if f == "DesignRules.dc.html":
            problems += [f"{f}: {x}" for x in rules_problems(t, s)]
    for f in ("components.css", "icons.css"):  # authored stylesheets: values only through var()
        body = re.sub(r"/\*.*?\*/", "", (MOCK / f).read_text(), flags=re.S)
        if Scan().raw(body):
            problems.append(f"{f}: raw colour (use var(--token))")
    problems = list(dict.fromkeys(problems))
    if check:
        for x in problems:
            print("FAIL", x)
        print("planned boards not drawn yet:", " ".join(sorted(planned)) or "none")
        print("design check:", "failed" if problems else "ok")
        sys.exit(1 if problems else 0)
    for f, txt in want.items():
        f.write_text(txt)
    for f in existing_twins - set(want):
        f.unlink()
    print(f"wrote tokens.css, logos.css, canvas.json and {len(twins)} dark twin(s)")


if __name__ == "__main__":
    main()
